export const getCurrentLanguage = () => {
  if (typeof window === 'undefined') return 'hi';
  return localStorage.getItem('gramsaksham_language') || 'hi';
};

export const setCurrentLanguage = (languageCode) => {
  if (typeof window === 'undefined') return;
  localStorage.setItem('gramsaksham_language', languageCode);
  window.dispatchEvent(new Event('languagechange'));
};

export const getTranslation = (languageCode = 'hi') => translations[languageCode] || translations.hi;
